//! Tailwind CSS & utility stylesheet extractor.
//!
//! Gathers all static utility classes across a component tree and bundles them into
//! a standalone, browser-native CSS stylesheet.

use std::collections::BTreeSet;
use strata_dom::NodeBlueprint;

/// Extracts class names from node blueprints and produces standalone CSS stylesheets.
pub struct CssExtractor;

impl CssExtractor {
    /// Extracts all unique class names present in a `NodeBlueprint` tree.
    pub fn collect_classes(blueprint: &NodeBlueprint) -> BTreeSet<String> {
        let mut classes = BTreeSet::new();
        Self::collect_recursive(blueprint, &mut classes);
        classes
    }

    fn collect_recursive(blueprint: &NodeBlueprint, out: &mut BTreeSet<String>) {
        match blueprint {
            NodeBlueprint::Element {
                classes, children, ..
            } => {
                for cls in classes {
                    for token in cls.split_whitespace() {
                        if !token.is_empty() {
                            out.insert(token.to_string());
                        }
                    }
                }
                for child in children {
                    Self::collect_recursive(child, out);
                }
            }
            NodeBlueprint::Fragment(children) => {
                for child in children {
                    Self::collect_recursive(child, out);
                }
            }
            _ => {}
        }
    }

    /// Generates a complete standalone CSS stylesheet for the collected classes.
    pub fn generate_stylesheet(classes: &BTreeSet<String>) -> String {
        let mut css = String::new();
        css.push_str("/* Generated by Strata Codegen JS */\n");
        css.push_str("*, *::before, *::after { box-sizing: border-box; margin: 0; padding: 0; }\n");
        css.push_str("body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; }\n\n");

        for class in classes {
            if let Some(rule) = Self::generate_rule_for_class(class) {
                css.push_str(&rule);
                css.push('\n');
            }
        }

        css
    }

    /// Escapes class names for CSS selector usage (handling colons, brackets, slashes).
    pub fn escape_selector(class: &str) -> String {
        let mut escaped = String::with_capacity(class.len() + 4);
        for ch in class.chars() {
            match ch {
                ':' | '[' | ']' | '/' | '%' | '.' | '#' => {
                    escaped.push('\\');
                    escaped.push(ch);
                }
                _ => escaped.push(ch),
            }
        }
        escaped
    }

    /// Maps common Tailwind / utility classes to static CSS rules.
    pub fn generate_rule_for_class(class: &str) -> Option<String> {
        let selector = format!(".{}", Self::escape_selector(class));

        // Pseudo-classes
        if let Some(rest) = class.strip_prefix("hover:") {
            let inner_selector = format!(".{}:hover", Self::escape_selector(class));
            return Self::generate_inner_declaration(rest).map(|decl| format!("{} {{ {} }}", inner_selector, decl));
        }
        if let Some(rest) = class.strip_prefix("focus:") {
            let inner_selector = format!(".{}:focus", Self::escape_selector(class));
            return Self::generate_inner_declaration(rest).map(|decl| format!("{} {{ {} }}", inner_selector, decl));
        }

        Self::generate_inner_declaration(class).map(|decl| format!("{} {{ {} }}", selector, decl))
    }

    fn generate_inner_declaration(class: &str) -> Option<String> {
        match class {
            // Display
            "flex" => Some("display: flex;".into()),
            "inline-flex" => Some("display: inline-flex;".into()),
            "grid" => Some("display: grid;".into()),
            "block" => Some("display: block;".into()),
            "inline-block" => Some("display: inline-block;".into()),
            "hidden" => Some("display: none;".into()),

            // Flex direction & alignment
            "flex-row" => Some("flex-direction: row;".into()),
            "flex-col" => Some("flex-direction: column;".into()),
            "items-center" => Some("align-items: center;".into()),
            "items-start" => Some("align-items: flex-start;".into()),
            "items-end" => Some("align-items: flex-end;".into()),
            "justify-center" => Some("justify-content: center;".into()),
            "justify-between" => Some("justify-content: space-between;".into()),
            "justify-start" => Some("justify-content: flex-start;".into()),
            "justify-end" => Some("justify-content: flex-end;".into()),

            // Text alignment & style
            "text-center" => Some("text-align: center;".into()),
            "text-left" => Some("text-align: left;".into()),
            "text-right" => Some("text-align: right;".into()),
            "font-bold" => Some("font-weight: 700;".into()),
            "font-semibold" => Some("font-weight: 600;".into()),
            "font-medium" => Some("font-weight: 500;".into()),

            // Sizing
            "w-full" => Some("width: 100%;".into()),
            "h-full" => Some("height: 100%;".into()),
            "w-screen" => Some("width: 100vw;".into()),
            "h-screen" => Some("height: 100vh;".into()),

            // Radius
            "rounded" => Some("border-radius: 0.25rem;".into()),
            "rounded-md" => Some("border-radius: 0.375rem;".into()),
            "rounded-lg" => Some("border-radius: 0.5rem;".into()),
            "rounded-full" => Some("border-radius: 9999px;".into()),

            // Positioning
            "relative" => Some("position: relative;".into()),
            "absolute" => Some("position: absolute;".into()),
            "fixed" => Some("position: fixed;".into()),

            // Arbitrary values e.g. w-[400px], bg-[#111]
            c if c.starts_with("w-[") && c.ends_with(']') => {
                let val = &c[3..c.len() - 1];
                Some(format!("width: {};", val))
            }
            c if c.starts_with("h-[") && c.ends_with(']') => {
                let val = &c[3..c.len() - 1];
                Some(format!("height: {};", val))
            }
            c if c.starts_with("bg-[") && c.ends_with(']') => {
                let val = &c[4..c.len() - 1];
                Some(format!("background-color: {};", val))
            }
            c if c.starts_with("text-[") && c.ends_with(']') => {
                let val = &c[6..c.len() - 1];
                Some(format!("color: {};", val))
            }
            c if c.starts_with("p-") => {
                let val = &c[2..];
                if let Ok(num) = val.parse::<f32>() {
                    Some(format!("padding: {}rem;", num * 0.25))
                } else {
                    None
                }
            }
            c if c.starts_with("m-") => {
                let val = &c[2..];
                if let Ok(num) = val.parse::<f32>() {
                    Some(format!("margin: {}rem;", num * 0.25))
                } else {
                    None
                }
            }
            c if c.starts_with("gap-") => {
                let val = &c[4..];
                if let Ok(num) = val.parse::<f32>() {
                    Some(format!("gap: {}rem;", num * 0.25))
                } else {
                    None
                }
            }
            _ => None,
        }
    }
}
